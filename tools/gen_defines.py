#!/usr/bin/env python3
"""Generate crates/ffh-data/src/defines_gen.rs: a typed struct with one field per
global define (data/json: global_defines, global_defines_alt, python_callback_defines, and this
game's own rules_defines), plus any define the DLL/Python reads that is absent from the data
(C++ returns 0).

Field name = lowercase define name. Int, flag and text defines are i32 (text defines are type
names resolved to indices, like C++ SetPostGlobalsGlobalDefines); numbers with a fraction or an
exponent are f32.

The defines the DLL/Python reads are found in the FFH2 reference sources (tools/fetch-reference.sh)
when REF_DIR exists; without them, the ones the current defines_gen.rs lists as absent from the
data are kept.

Usage: tools/gen_defines.py [REF_DIR]
"""
import glob
import os
import re
import sys

import jsonc

REF = sys.argv[1] if len(sys.argv) > 1 else "/home/user/ref"
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.normpath(os.path.join(HERE, "..", "data", "json"))
OUT = os.path.normpath(os.path.join(HERE, "..", "crates", "ffh-data", "src", "defines_gen.rs"))
DLL = os.path.join(REF, "ffh2", "CvGameCoreDLL")
PY = os.path.join(REF, "ffh2", "Assets", "python")
FILES = ["global_defines.jsonc", "global_defines_alt.jsonc", "python_callback_defines.jsonc", "rules_defines.jsonc"]
ABSENT_NOTE = "  // not in the data: C++ reads 0"

RUST_KW = {"type", "move", "loop", "match", "fn", "impl", "mod", "use", "ref", "self", "super", "static", "const"}


def read_defines():
    """(kinds by define name, names in file order)."""
    kinds, order = {}, []
    for f in FILES:
        for name, value in jsonc.load(os.path.join(DATA, f)).items():
            if name not in kinds:
                order.append(name)
            kinds[name] = "f32" if isinstance(value, float) else "i32"
    return kinds, order


def absent_from_sources(kinds):
    """Defines the DLL/Python reads that the data lacks, by kind; None without the sources."""
    if not os.path.isdir(DLL):
        return None
    used_int, used_float = set(), set()
    srcs = glob.glob(os.path.join(DLL, "*.cpp")) + glob.glob(os.path.join(DLL, "*.h")) \
        + glob.glob(os.path.join(PY, "**", "*.py"), recursive=True)
    for p in srcs:
        s = open(p, encoding="latin-1").read()
        used_int.update(re.findall(r'getDefineINT\(\s*"(\w+)"', s))
        used_float.update(re.findall(r'getDefineFLOAT\(\s*"(\w+)"', s))
    return {name: ("f32" if name in used_float else "i32") for name in sorted((used_int | used_float) - set(kinds))}


def absent_from_current():
    """The defines the current defines_gen.rs marks as absent from the data, with their kinds."""
    s = open(OUT, encoding="utf-8").read()
    fields = {m.group(1): m.group(2) for m in re.finditer(r"pub (\w+): (i32|f32),\s*// not in", s)}
    names = {m.group(1): m.group(2) for m in re.finditer(r'(\w+): m\.(?:int|float)\("(\w+)"\)', s)}
    return {names[f]: k for f, k in fields.items()}


def main():
    kinds, order = read_defines()
    absent = absent_from_sources(kinds)
    if absent is None:
        print(f"no reference sources at {DLL}: keeping the absent defines defines_gen.rs lists")
        absent = {n: k for n, k in absent_from_current().items() if n not in kinds}
    for name in sorted(absent):
        order.append(name)
        kinds[name] = absent[name]

    def field(name):
        f = name.lower()
        return f + "_" if f in RUST_KW else f

    lines = []
    lines.append("//! GENERATED by tools/gen_defines.py -- do not edit by hand.")
    lines.append("//! One field per global define. Text defines hold the resolved type index (-1 if none),")
    lines.append("//! exactly like C++ `GC.getDefineINT` after `SetPostGlobalsGlobalDefines`.\n")
    lines.append("use crate::defines::DefineMap;\n")
    lines.append("#[derive(Debug, Clone, Default)]")
    lines.append("pub struct Defines {")
    for name in order:
        note = ABSENT_NOTE if name in absent else ""
        lines.append(f"    pub {field(name)}: {kinds[name]},{note}")
    lines.append("}\n")
    lines.append("impl Defines {")
    lines.append("    pub fn from_map(m: &DefineMap) -> Self {")
    lines.append("        Defines {")
    for name in order:
        getter = "float" if kinds[name] == "f32" else "int"
        lines.append(f'            {field(name)}: m.{getter}("{name}"),')
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(order)} defines ({len(absent)} read by the C++ but absent from the data: {sorted(absent)})")


if __name__ == "__main__":
    main()
