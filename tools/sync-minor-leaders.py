#!/usr/bin/env python3
"""Register the approved minor-leader concepts as non-selectable breakaway leaders.

The supplemental files append each batch in order without shifting existing leader IDs.
Run this after changing docs/minor-leaders/concepts.json. Use --check to verify the committed data.
"""
import argparse
import copy
import json
from pathlib import Path
import re
import sys

import jsonc

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs/minor-leaders/concepts.json"
CARDS = ROOT / "data/json/cards"
OUTPUTS = (CARDS / "zz_minor_leaders.jsonc", CARDS / "zzz_minor_leaders.jsonc")
BATCH_SIZE = 5
HEADER = """// The 105 approved minor leaders: five for each original civilization.
// Generated by tools/sync-minor-leaders.py from docs/minor-leaders/concepts.json.
// Appended after existing supplemental entries, preserving their registered leader IDs.
// No civilization lists these leaders, so no new game starts with them.
// Personal traits are exact; civilization traits remain inherited.
// AI personalities start with a complete same-civilization major-leader personality,
// chosen by alignment and trait overlap, then adjust peace, force building and research
// flavors to the new alignment and traits. Personal identity fields are not inherited.
"""

IDENTITY = {
    "type", "description", "civilopedia", "help", "strategy", "button", "graphical_only",
    "minor_leader_of", "preferred_breakaway", "traits", "alignment", "female",
    "permanent_trait", "cultural_aggression", "attitude_from_females", "attitude_from_males",
    "attitude_to_females", "attitude_to_males",
}
RELIGION_FIELDS = {"favorite_religion", "favorite_early_religion", "religion_weight_modifiers"}
TRAIT_FLAVORS = {
    "TRAIT_PHILOSOPHICAL": {"FLAVOR_SCIENCE": 15},
    "TRAIT_AGGRESSIVE": {"FLAVOR_MILITARY": 20},
    "TRAIT_SPIRITUAL": {"FLAVOR_RELIGION": 15},
    "TRAIT_EXPANSIVE": {"FLAVOR_GROWTH": 15},
    "TRAIT_INDUSTRIOUS": {"FLAVOR_PRODUCTION": 15},
    "TRAIT_CREATIVE": {"FLAVOR_CULTURE": 15},
    "TRAIT_FINANCIAL": {"FLAVOR_GOLD": 15},
    "TRAIT_ORGANIZED": {"FLAVOR_PRODUCTION": 10, "FLAVOR_GROWTH": 10},
    "TRAIT_CHARISMATIC": {"FLAVOR_CULTURE": 10, "FLAVOR_MILITARY": 10},
    "TRAIT_ARCANE": {"FLAVOR_SCIENCE": 15},
    "TRAIT_MAGIC_RESISTANT": {"FLAVOR_MILITARY": 10},
    "TRAIT_RAIDERS": {"FLAVOR_MILITARY": 20},
    "TRAIT_SUMMONER": {"FLAVOR_SCIENCE": 15, "FLAVOR_MILITARY": 15},
    "TRAIT_DEFENDER": {"FLAVOR_MILITARY": 15, "FLAVOR_PRODUCTION": 10},
    "TRAIT_INGENUITY": {"FLAVOR_PRODUCTION": 15},
    "TRAIT_TOLERANT": {"FLAVOR_CULTURE": 10, "FLAVOR_GROWTH": 10},
}
MINOR_DIPLOMACY = {
    "FIRST_CONTACT": "I speak for [OUR_EMPIRE]. Our decisions are our own.",
    "GREETINGS": "What have you come to discuss, [CT_NAME]?",
    "DECLARE_WAR": "Our dispute will now be settled by force.",
    "REFUSE_TO_TALK": "There will be no talks between us today.",
    "ACCEPT": "We accept these terms.",
    "THANKS": "We acknowledge your gift. Thank you.",
    "NO_DEAL": "Those terms do not serve our interests.",
    "PEACE": "We accept peace. Let the fighting end.",
    "NO_PEACE": "We are not ready to make peace.",
    "REJECT": "We will not submit to that demand.",
    "WORST_ENEMY": "Your dealings with our enemies concern us.",
    "WORST_ENEMY_TRADING": "Your trade with our enemies will not go unnoticed.",
    "NUKES": "We possess weapons you would be wise to consider.",
    "UNIT_BRAG": "Do not underestimate the forces at our command.",
}


def definitions():
    concepts = json.loads(SOURCE.read_text())
    civilizations = {c["type"]: c for c in jsonc.table("civilizations")}
    existing = jsonc.table("leader_heads")
    for path in sorted(CARDS.glob("*.jsonc")):
        if path not in OUTPUTS:
            existing += jsonc.load(path).get("leader_heads", [])
    leaders = {l["type"]: l for l in existing}
    religions = [r["type"] for r in jsonc.table("religions")]
    batches = [{"leader_heads": [], "text": {}} for _ in OUTPUTS]
    for civ in concepts:
        assert len(civ["leaders"]) == BATCH_SIZE * len(batches), civ["civilization"]
        own = [leaders[name] for name, enabled in civilizations[civ["civilization"]]["leaders"].items() if enabled]
        for index, concept in enumerate(civ["leaders"]):
            alignment = "ALIGNMENT_" + concept["alignment"].upper()
            traits = set(concept["traits"])
            baseline = max(own, key=lambda l: 3 * (l.get("alignment") == alignment) + 2 * len(traits.intersection(l.get("traits", {}))))
            info = {k: copy.deepcopy(v) for k, v in baseline.items() if k not in IDENTITY}
            name = "LEADER_" + concept["id"].upper()
            assert name not in leaders, f"Existing leader ID: {name}"
            key = "TXT_KEY_" + name
            header = {"type": name, "description": key, "civilopedia": key + "_PEDIA",
                      "minor_leader_of": civ["civilization"], "preferred_breakaway": True}
            if baseline.get("alignment") != alignment:
                # A new moral outlook does not inherit the old ruler's religious prohibitions.
                for field in RELIGION_FIELDS:
                    info.pop(field, None)
            if "TRAIT_AGNOSTIC" in traits.union(concept["inherited_traits"]):
                for field in RELIGION_FIELDS:
                    info.pop(field, None)
                info["religion_weight_modifiers"] = {r: -100 for r in religions}
            elif civ["civilization"] == "CIVILIZATION_MERCURIANS":
                # Talvek's tyranny still fights demons; evil does not make him a Veil ally.
                info.setdefault("religion_weight_modifiers", {})["RELIGION_THE_ASHEN_VEIL"] = -100
            if concept["alignment"] == "Good" and info.get("favorite_civic") == "CIVIC_SLAVERY":
                info["favorite_civic"] = "CIVIC_LIBERTY"
            militant = bool(traits.intersection({"TRAIT_AGGRESSIVE", "TRAIT_RAIDERS"}))
            info["base_peace_weight"] = {"Good": 8, "Neutral": 5, "Evil": 2}[concept["alignment"]]
            info["base_attitude"] = {"Good": 1, "Neutral": 0, "Evil": -1}[concept["alignment"]]
            info["limited_war_rand"] = {"Good": 200, "Neutral": 150, "Evil": 100}[concept["alignment"]] - (50 if militant else 0)
            info["max_war_rand"] = {"Good": 100, "Neutral": 70, "Evil": 40}[concept["alignment"]] - (20 if militant else 0)
            info["build_unit_prob"] = 40 if militant else 30 if "TRAIT_DEFENDER" in traits else 25
            info["make_peace_rand"] = {"Good": 20, "Neutral": 30, "Evil": 50}[concept["alignment"]]
            info["demand_rebuked_sneak_prob"] = {"Good": 0, "Neutral": 10, "Evil": 20}[concept["alignment"]]
            info["demand_rebuked_war_prob"] = {"Good": 0, "Neutral": 10, "Evil": 20}[concept["alignment"]]
            flavors = info.setdefault("flavors", {})
            for trait in concept["traits"]:
                for flavor, value in TRAIT_FLAVORS.get(trait, {}).items():
                    flavors[flavor] = max(flavors.get(flavor, 0), value)
            if "TRAIT_AGNOSTIC" in traits.union(concept["inherited_traits"]):
                flavors["FLAVOR_RELIGION"] = 0
            info["female"] = bool(re.search(r"\b(?:woman|female(?:-presenting)?|feminine)\b", concept["portrait"], re.I))
            info["alignment"] = alignment
            info["traits"] = {t: True for t in concept["traits"]}
            leader = {**header, **info}
            leaders[name] = leader
            batch = batches[index // BATCH_SIZE]
            batch["leader_heads"].append(leader)
            text = batch["text"]
            text[key] = concept["name"]
            text[key + "_PEDIA"] = concept["epithet"] + "[NEWLINE][NEWLINE]" + concept["backstory"]
    batches[0]["text"].update({"TXT_KEY_MINOR_DIPLO_" + moment: line for moment, line in MINOR_DIPLOMACY.items()})
    return batches


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    status = 0
    for index, (path, batch) in enumerate(zip(OUTPUTS, definitions(), strict=True)):
        count = len(batch["leader_heads"])
        header = HEADER
        if index:
            header = f"// {count} additional minor leaders, five for each original civilization.\n" + HEADER.split("\n", 1)[1]
        contents = header + json.dumps(batch, indent=2, ensure_ascii=False) + "\n"
        if not args.check:
            path.write_text(contents)
            print(f"Wrote {count} minor leaders and their names and backstories to {path.relative_to(ROOT)}.")
        elif not path.exists() or path.read_text() != contents:
            print(f"{path.relative_to(ROOT)} is stale. Run {Path(__file__).name}.", file=sys.stderr)
            status = 1
        else:
            print(f"{path.relative_to(ROOT)} matches the concepts for {count} minor leaders.")
    return status


if __name__ == "__main__":
    raise SystemExit(main())
