def main():
    spheres = [(f"sphere_{k}", ORB.format(c=c, s=s)) for k, c, s in SPHERES]
    blds = [(f"building_{k}", d) for k, d in BUILDINGS if d]
    promos = [(f"promo_{k}", d) for k, d in PROMOS]
    seq = spheres + MISC + blds[:6] + STAGES + blds[6:] + promos
    # STAGES holds 13: the sheet after the stages is shifted by one building, which is fine.
    n = (len(seq) + 15) // 16
    pad = n * 16 - len(seq)
    if pad:
        raise SystemExit(f"{len(seq)} icons: {pad} short of {n} full sheets")
    out = Path(__file__).parent
    for i in range(n):
        part = seq[16 * i: 16 * (i + 1)]
