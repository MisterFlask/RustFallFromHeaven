"""Ships the finished animation sets to the play client (the battle screens, crates/ffh-play/assets/app/battle_stage.js).

For every `final_<key>/` with all four sheets (idle, strike, flinch, death) it writes
`crates/ffh-play/assets/app/anim/<sprite>_<anim>.png` (the strip, 160 px a frame, as an 8-bit palette PNG: about a
quarter of the size of the RGBA sheet for a mean colour error of about 4/255), where <sprite> is the M7 sprite's short
name (`unit_ogre_embers.png` -> `ogre_embers`), and regenerates `crates/ffh-play/assets/app/anim_sets.js`: which sprites
have a set (ANIM_SETS, `left` when the set looks lower-left) and which M7 sprites look lower-left at all (FACES_LEFT,
from the unit files where there is one, else the roster classification, `roster_classified.json`).

  python lib/export_game.py [--only key,key] [--dry-run]
"""
import argparse, json, sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent
APP = REPO / "crates/ffh-play/assets/app"
ANIMS = ("idle", "strike", "flinch", "death")


def sets():
    """[(key, sprite short name, facing)] of every complete set."""
    out = []
    for d in sorted(ROOT.glob("final_*")):
        key = d.name[len("final_"):]
        if key.endswith("_nofx") or not d.is_dir() or not all((d / f"sheet_{a}.png").exists() for a in ANIMS):
            continue
        uf = ROOT / "units" / f"{key}.json"
        if uf.exists():
            u = json.loads(uf.read_text(encoding="utf-8"))
            if u.get("legacy"):
                continue
            short = Path(u["sprite"]).stem.removeprefix("unit_")
        else:
            short = key
        m = json.loads((d / "strike" / "manifest.json").read_text(encoding="utf-8"))
        out.append((key, short, m.get("facing", "lower-right")))
    return out


def faces_left():
    left = {s["name"].removeprefix("unit_") for s in json.loads((ROOT / "roster_classified.json").read_text(encoding="utf-8"))
            if s["facing"] == "lower-left"}
    for uf in (ROOT / "units").glob("*.json"):
        u = json.loads(uf.read_text(encoding="utf-8"))
        if u.get("legacy"):
            continue
        short = Path(u["sprite"]).stem.removeprefix("unit_")
        (left.add if u["facing"] == "lower-left" else left.discard)(short)
    return sorted(left)


def strip(src, dst):
    im = Image.open(src).convert("RGBA")
    q = im.quantize(colors=255, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    q.save(dst, "PNG", optimize=True)
    return dst.stat().st_size


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    only = set(filter(None, a.only.split(",")))
    found = [s for s in sets() if not only or s[0] in only]
    total = 0
    for key, short, _ in found:
        for an in ANIMS:
            if not a.dry_run:
                total += strip(ROOT / f"final_{key}" / f"sheet_{an}.png", APP / "anim" / f"{short}_{an}.png")
    shipped = sorted({s for _, s, _ in sets()})
    facing = {s: f for _, s, f in sets()}
    js = ("// Generated by anim-sprint/lib/export_game.py (do not edit): the M7 unit sprites that have battle animations\n"
          "// (`app/anim/<sprite>_<idle|strike|flinch|death>.png`; `left`: the set looks lower-left) and every M7 unit\n"
          "// sprite that looks lower-left (the rest look lower-right).\n"
          "export const ANIM_SETS = {\n"
          + "".join(f"  {s}: {{{' left: true ' if facing[s] == 'lower-left' else ''}}},\n" for s in shipped)
          + "};\n\nexport const FACES_LEFT = new Set([\n"
          + "".join(f'  "{s}",\n' for s in faces_left()) + "]);\n")
    if not a.dry_run:
        (APP / "anim_sets.js").write_text(js, encoding="utf-8", newline="\n")
    print(json.dumps({"sets": len(found), "shipped": len(shipped), "bytes_written": total, "faces_left": len(faces_left())}))


if __name__ == "__main__":
    sys.exit(main())
